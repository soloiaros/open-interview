// Writing rules adapted from stop-slop (github.com/hardikpandya/stop-slop, MIT).
// Appended to every prompt that produces prose a person will read.
export const WRITING_RULES = `Writing rules for any prose you produce:
1. Cut filler phrases. No throat-clearing openers, emphasis crutches, or adverbs.
2. No formulaic structures: no "not X, it's Y" contrasts, no negative listings, no dramatic fragments, no rhetorical setups.
3. Active voice. A person does each action. Objects do not perform human actions ("the data tells us").
4. Be specific. Name the thing, the person, the number. No vague declaratives, no lazy "always/never/every".
5. Address the reader as "you" where it fits. Specifics beat abstractions.
6. Vary sentence length. Two items beat three. No em dashes.
7. State facts directly. No softening, no hand-holding, no pull-quote lines.
8. No sentence starts with "Here's", "This is why", or a question word used as a setup.`;
